// Token Radar — the valuation model (radar-2).
//
// One sealed snapshot in, one ranked board out. Every number below comes from
// the snapshot's own figures: TVL, 7-day TVL change, listing age, chain count
// and category. No protocol name is ever special-cased.
//
//   base       = tvl_usd x BASE_MULTIPLE
//   growth     = clamp(change_7d, -50, 150) per cent
//   growthMult = 1 + (growth / 100) x GROWTH_WEIGHT
//   maturity   = 0.5 + min(age_days, 730) / 730 x 0.5     (age unknown: 365)
//   chainMult  = 1 + min(chains, 5) x 0.03                (more chains, wider reach)
//   discount   = 0.5 for wrapped / staked / bridged products, else 1
//   implied    = max(1, round(base x growthMult x maturity x chainMult x discount))
//
// The discount is the model's judgement call, stated openly — and it is not
// enough on its own: a bridge, a liquid-staking token or a restaked product
// is a wrapped or staked form of a token that already trades, so the board
// does not rank those protocols at all. They are listed separately, with the
// reason, in the dashboard's "Not ranked" section: a radar shows the whole
// sky, with the weather marked, and a launch candidate is a standalone
// protocol whose token does not exist yet. The discount constant stays in the
// model so the sandbox can still price a derivative row if one is ever added.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's constants, as the dashboard states them and the sandbox may change them. */
export interface ModelConstants {
  base_multiple: number;
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  unknown_age_days: number;
  chain_step: number;
  chain_cap: number;
  derivative_discount: number;
}

export const MODEL: ModelConstants = {
  base_multiple: 0.3,
  growth_weight: 0.7,
  growth_floor: -50,
  growth_cap: 150,
  maturity_floor: 0.5,
  maturity_range: 0.5,
  maturity_days: 730,
  unknown_age_days: 365,
  chain_step: 0.03,
  chain_cap: 5,
  derivative_discount: 0.5,
};

/** The model's version label: the dashboard names it. */
export const MODEL_VERSION = 'radar-2';

/** How many live-token protocols the Live view carries, by market cap. */
export const LIVE_ROWS = 24;

